"""
Report Generator
Creates downloadable PDF market reports from agent analysis.
"""

from fpdf import FPDF
from datetime import datetime
import re
import io


class MarketReportPDF(FPDF):
    """Custom PDF class for market intelligence reports."""
    
    def header(self):
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(0, 180, 150)
        self.cell(0, 8, "Market Intelligence Agent", align="L")
        self.set_font("Helvetica", "", 9)
        self.set_text_color(130, 130, 130)
        self.cell(0, 8, f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}", align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(50, 50, 50)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)
    
    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(100, 100, 100)
        self.cell(0, 10, f"Quadra Systems | Confidential | Page {self.page_no()}", align="C")


def generate_pdf_report(
    query: str,
    response: str,
    tools_used: list,
    metadata: dict,
    broker_name: str = None,
) -> bytes:
    """
    Generate a PDF report from an agent analysis.
    
    Args:
        query: The user's original question
        response: The agent's analysis text
        tools_used: List of tools called
        metadata: Run metadata (model, latency, etc.)
        broker_name: Optional broker name for personalization
    
    Returns:
        PDF file as bytes
    """
    pdf = MarketReportPDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    
    # Title
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(0, 180, 150)
    pdf.cell(0, 12, "Market Analysis Report", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    
    # Metadata line
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(130, 130, 130)
    meta_line = f"Date: {datetime.now().strftime('%B %d, %Y')} | Model: {metadata.get('model', 'N/A')} | Latency: {metadata.get('elapsed_seconds', 0):.1f}s"
    if broker_name:
        meta_line += f" | Prepared for: {broker_name}"
    pdf.cell(0, 6, meta_line, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    
    # Query
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(40, 40, 40)
    pdf.cell(0, 8, "Query", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(60, 60, 60)
    pdf.multi_cell(0, 6, query)
    pdf.ln(4)
    
    # Tools used
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(40, 40, 40)
    pdf.cell(0, 8, "Data Sources Used", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(80, 80, 80)
    for tool in tools_used:
        tool_name = tool.get("tool", "unknown") if isinstance(tool, dict) else str(tool)
        pdf.cell(0, 5, f"    - {tool_name}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    
    # Main analysis
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(40, 40, 40)
    pdf.cell(0, 8, "Analysis", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    
    # Parse and render the response (handle markdown-style formatting)
    _render_markdown_to_pdf(pdf, response)
    
    # Disclaimer
    pdf.ln(8)
    pdf.set_draw_color(50, 50, 50)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(120, 120, 120)
    pdf.multi_cell(0, 4,
        "Disclaimer: This report is generated by an AI agent using real-time market data. "
        "It is for informational purposes only and does not constitute financial advice. "
        "Past performance does not guarantee future results. Always consult a qualified "
        "financial advisor before making investment decisions."
    )
    
    # Output as bytes
    try:
        return bytes(pdf.output())
    except Exception:
        # Fallback: return a simple error PDF
        fallback = FPDF()
        fallback.add_page()
        fallback.set_font("Helvetica", "", 12)
        fallback.cell(0, 10, "Report generation encountered an issue. Please try again.")
        return bytes(fallback.output())


def _render_markdown_to_pdf(pdf: FPDF, text: str):
    """Render markdown-ish text into the PDF with basic formatting."""
    
    # Strip problematic characters that fpdf can't handle
    text = text.replace('`', '')
    text = text.replace('│', '|')
    text = text.replace('─', '-')
    text = text.replace('┌', '+').replace('┐', '+').replace('└', '+').replace('┘', '+')
    # Strip emoji and non-ASCII that fpdf can't render
    text = text.encode('ascii', 'ignore').decode('ascii')
    # Clean up rupee symbol and other currency
    text = text.replace('\u20b9', 'Rs.').replace('\u20ac', 'EUR').replace('\u00a3', 'GBP')
    
    lines = text.split("\n")
    
    for line in lines:
        stripped = line.strip()
        
        if not stripped:
            pdf.ln(3)
            continue
        
        try:
            # Headers
            if stripped.startswith("### "):
                pdf.ln(2)
                pdf.set_font("Helvetica", "B", 11)
                pdf.set_text_color(0, 150, 130)
                pdf.cell(0, 7, stripped[4:], new_x="LMARGIN", new_y="NEXT")
            elif stripped.startswith("## "):
                pdf.ln(3)
                pdf.set_font("Helvetica", "B", 13)
                pdf.set_text_color(0, 150, 130)
                pdf.cell(0, 8, stripped[3:], new_x="LMARGIN", new_y="NEXT")
            elif stripped.startswith("# "):
                pdf.ln(3)
                pdf.set_font("Helvetica", "B", 14)
                pdf.set_text_color(0, 180, 150)
                pdf.cell(0, 9, stripped[2:], new_x="LMARGIN", new_y="NEXT")
            # Bullet points
            elif stripped.startswith("- ") or stripped.startswith("* "):
                pdf.set_font("Helvetica", "", 10)
                pdf.set_text_color(60, 60, 60)
                content = re.sub(r'\*\*(.*?)\*\*', r'\1', stripped[2:])
                pdf.cell(0, 5, f"  - {content}", new_x="LMARGIN", new_y="NEXT")
            # Bold lines
            elif stripped.startswith("**") and stripped.endswith("**"):
                pdf.set_font("Helvetica", "B", 11)
                pdf.set_text_color(40, 40, 40)
                clean = stripped.strip("* ")
                pdf.cell(0, 6, clean, new_x="LMARGIN", new_y="NEXT")
            # Regular text
            else:
                pdf.set_font("Helvetica", "", 10)
                pdf.set_text_color(60, 60, 60)
                content = re.sub(r'\*\*(.*?)\*\*', r'\1', stripped)
                content = re.sub(r'\*(.*?)\*', r'\1', content)
                # Use cell for single lines, safer than multi_cell
                if len(content) < 90:
                    pdf.cell(0, 5, content, new_x="LMARGIN", new_y="NEXT")
                else:
                    pdf.multi_cell(0, 5, content)
        except Exception:
            # Skip any line that causes rendering issues
            continue
